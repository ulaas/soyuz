<#
.SYNOPSIS
  Creates a realistic, privacy-safe demo folder tree for Soyuz screenshots and demos.

.DESCRIPTION
  Everything is generated: photos are procedurally drawn landscapes, audio is synthesized,
  documents and code are sample text, and timestamps are spread over the last months from a
  fixed seed, so two runs produce the same tree. Nothing is copied from your own folders.

  Layout:
    Documents\  Reports, Notes, Recipes, Travel, Manuals (Markdown, CSV, text, a small PDF)
    Photos\     landscapes (JPEG), 2026 Summer trip\ (more JPEGs), Screenshots\ (PNG)
    Projects\   orbit-tracker (Rust), website (HTML/CSS/JS/SVG), data-tools (Python, JSON)
    Music\      synthesized WAV files (waveform preview)
    Downloads\  a zip of some photos, a CSV export, a large data file (for job demos)
    Archive\    an older copy of Documents\Reports (for the folder-compare screenshot)

.PARAMETER Root
  Where to create the tree. Defaults to "<drive of this repo>:\SoyuzDemo" so that paths in
  screenshots are short and contain no user name. The folder is replaced if it exists.

.PARAMETER BigFileMB
  Size of Downloads\Telemetry dump.dat (used to show a running copy job). 0 skips it.

.EXAMPLE
  ./scripts/demo-fixture.ps1                       # -> E:\SoyuzDemo (or C:\SoyuzDemo)
  ./scripts/demo-fixture.ps1 -Root D:\Demo -BigFileMB 0
#>
[CmdletBinding()]
