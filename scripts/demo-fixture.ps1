    param($t, $len)
    $env = [Math]::Exp(-3 * ($t % 1.0))
    $f = @(523.25, 659.25, 783.99)[[Math]::Min(2, [int][Math]::Floor($t))]
    0.5 * $env * [Math]::Sin(2 * [Math]::PI * $f * $t)
}
