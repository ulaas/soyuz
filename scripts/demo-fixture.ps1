function C([string]$hex) { [System.Drawing.ColorTranslator]::FromHtml($hex) }

function Save-Jpeg([System.Drawing.Bitmap]$bmp, [string]$path, [int]$quality = 86) {
    $codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object MimeType -eq 'image/jpeg'
    $params = [System.Drawing.Imaging.EncoderParameters]::new(1)
    $params.Param[0] = [System.Drawing.Imaging.EncoderParameter]::new([System.Drawing.Imaging.Encoder]::Quality, [long]$quality)
    $bmp.Save($path, $codec, $params)
}

function Draw-Ridge($g, [int]$w, [int]$h, [double]$base, [double]$amp, [string]$color, [int]$seed) {
    $r = [System.Random]::new($seed)
    $pts = [System.Collections.Generic.List[System.Drawing.PointF]]::new()
    $pts.Add([System.Drawing.PointF]::new(0, $h))
    $y = $base
    $p1 = $r.NextDouble() * 6; $p2 = $r.NextDouble() * 6
    for ($x = 0; $x -le $w; $x += 8) {
        $t = $x / $w
        $y = $base - $amp * (0.55 * [Math]::Sin($t * 7 + $p1) + 0.3 * [Math]::Sin($t * 17 + $p2) + 0.15 * [Math]::Sin($t * 41)) - $r.NextDouble() * $amp * 0.08
        $pts.Add([System.Drawing.PointF]::new($x, $y))
    }
    $pts.Add([System.Drawing.PointF]::new($w, $h))
    $brush = [System.Drawing.SolidBrush]::new((C $color))
    $g.FillPolygon($brush, $pts.ToArray())
    $brush.Dispose()
}

function New-Landscape([string]$path, [string]$skyTop, [string]$skyBottom, [string]$sun, [string[]]$ridges, [int]$seed, [switch]$Stars, [switch]$Aurora, [switch]$City, [switch]$Water) {
    $w = 1600; $h = 1067
    $bmp = [System.Drawing.Bitmap]::new($w, $h)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $rect = [System.Drawing.Rectangle]::new(0, 0, $w, $h)
    $sky = [System.Drawing.Drawing2D.LinearGradientBrush]::new($rect, (C $skyTop), (C $skyBottom), 90.0)
    $g.FillRectangle($sky, $rect)
    $r = [System.Random]::new($seed)
    if ($Stars) {
        for ($i = 0; $i -lt 260; $i++) {
            $a = 80 + $r.Next(0, 175)
            $b = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb($a, 255, 255, 255))
            $s = 1 + $r.NextDouble() * 2
            $g.FillEllipse($b, [single]($r.NextDouble() * $w), [single]($r.NextDouble() * $h * 0.6), [single]$s, [single]$s)
            $b.Dispose()
        }
    }
    if ($Aurora) {
        for ($k = 0; $k -lt 3; $k++) {
            $col = @((C '#3dffb0'), (C '#7cf7ff'), (C '#b48cff'))[$k]
            for ($x = 0; $x -lt $w; $x += 3) {
                $t = $x / $w
                $top = 140 + 90 * [Math]::Sin($t * 5 + $k * 1.7) + 40 * [Math]::Sin($t * 13 + $k)
                $len = 160 + 120 * [Math]::Sin($t * 3 + $k * 2.1)
                $pen = [System.Drawing.Pen]::new([System.Drawing.Color]::FromArgb(22, $col), 3)
                for ($j = 0; $j -lt 4; $j++) { $g.DrawLine($pen, [single]$x, [single]($top + $j * 12), [single]$x, [single]($top + $len)) }
                $pen.Dispose()
            }
        }
    }
    if ($sun) {
        for ($i = 6; $i -ge 1; $i--) {
            $rad = 60 + $i * 38
            $b = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb([int](14 + (6 - $i) * 4), (C $sun)))
            $g.FillEllipse($b, [single](1060 - $rad), [single](430 - $rad), [single](2 * $rad), [single](2 * $rad))
            $b.Dispose()
        }
        $b = [System.Drawing.SolidBrush]::new((C $sun))
        $g.FillEllipse($b, 1000, 370, 120, 120)
        $b.Dispose()
    }
    $n = $ridges.Count
    for ($i = 0; $i -lt $n; $i++) {
        $base = $h * (0.52 + 0.4 * $i / [Math]::Max(1, $n))
        Draw-Ridge $g $w $h $base (150 - $i * 25) $ridges[$i] ($seed + $i * 11)
    }
    if ($City) {
        for ($x = 0; $x -lt $w; ) {
            $bw = 50 + $r.Next(0, 90); $bh = 140 + $r.Next(0, 420)
            $b = [System.Drawing.SolidBrush]::new((C '#0d1424'))
            $g.FillRectangle($b, $x, $h - $bh, $bw - 6, $bh)
            $b.Dispose()
            for ($wy = $h - $bh + 14; $wy -lt $h - 10; $wy += 18) {
                for ($wx = $x + 8; $wx -lt $x + $bw - 16; $wx += 14) {
                    if ($r.NextDouble() -lt 0.42) {
                        $lb = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(200 + $r.Next(0, 55), 255, 214, 130))
                        $g.FillRectangle($lb, $wx, $wy, 6, 9)
                        $lb.Dispose()
                    }
                }
            }
            $x += $bw
        }
    }
    if ($Water) {
        $wt = [int]($h * 0.72)
        $wrect = [System.Drawing.Rectangle]::new(0, $wt, $w, $h - $wt)
        $wb = [System.Drawing.Drawing2D.LinearGradientBrush]::new($wrect, (C $skyBottom), (C $skyTop), 90.0)
        $g.FillRectangle($wb, $wrect)
        for ($i = 0; $i -lt 140; $i++) {
            $y = $wt + $r.NextDouble() * ($h - $wt)
            $x = $r.NextDouble() * $w
            $pen = [System.Drawing.Pen]::new([System.Drawing.Color]::FromArgb(60, 255, 255, 255), 2)
            $g.DrawLine($pen, [single]$x, [single]$y, [single]($x + 30 + $r.Next(0, 80)), [single]$y)
            $pen.Dispose()
        }
    }
    $g.Dispose()
    Save-Jpeg $bmp $path
    $bmp.Dispose()
}

