if (Test-Path -LiteralPath $Root) {
    if (-not (Test-Path -LiteralPath (Join-Path $Root '.soyuz-demo'))) {
        throw "$Root exists and is not a Soyuz demo tree (no .soyuz-demo marker); refusing to replace it."
    }
    Remove-Item -LiteralPath $Root -Recurse -Force
}
New-Item -ItemType Directory -Path $Root | Out-Null
Set-Content -LiteralPath (Join-Path $Root '.soyuz-demo') -Value 'Generated by scripts/demo-fixture.ps1' -Encoding utf8
(Get-Item -LiteralPath (Join-Path $Root '.soyuz-demo')).Attributes = 'Hidden'

$rng = [System.Random]::new(1957)
$now = Get-Date -Year 2026 -Month 10 -Day 6 -Hour 17 -Minute 42 -Second 0

function New-Dir([string]$rel) {
    $p = Join-Path $Root $rel
    New-Item -ItemType Directory -Force -Path $p | Out-Null
    $p
}

function Set-Age([string]$path, [double]$maxDays, [double]$minDays = 0) {
    $age = $minDays + $rng.NextDouble() * ($maxDays - $minDays)
    $t = $now.AddDays(-$age).AddMinutes(-$rng.Next(0, 600))
    $item = Get-Item -LiteralPath $path
    $item.CreationTime = $t
    $item.LastWriteTime = $t
}

function Write-Text([string]$rel, [string]$text, [double]$maxDays = 60, [double]$minDays = 0) {
    $p = Join-Path $Root $rel
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $p) | Out-Null
    [System.IO.File]::WriteAllText($p, ($text -replace "`r`n", "`n").TrimStart("`n"), [System.Text.UTF8Encoding]::new($false))
    Set-Age $p $maxDays $minDays
}

