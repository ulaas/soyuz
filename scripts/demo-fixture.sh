/// A ground station on the WGS-84 ellipsoid.
pub struct Station {
    pub name: String,
    pub lat: f64,
    pub lon: f64,
    pub alt_m: f64,
}

/// One visible pass.
pub struct Pass {
    pub start_min: f64,
    pub max_elevation: f64,
}

/// A simplified circular orbit.
pub struct Orbit {
    altitude_km: f64,
    inclination_deg: f64,
}

impl Orbit {
    pub fn circular(altitude_km: f64, inclination_deg: f64) -> Self {
        Orbit { altitude_km, inclination_deg }
    }

    /// Orbital period in minutes (Kepler's third law).
    pub fn period_min(&self) -> f64 {
        const MU: f64 = 398_600.4418;
        let a = 6_371.0 + self.altitude_km;
        2.0 * std::f64::consts::PI * (a.powi(3) / MU).sqrt() / 60.0
    }

    pub fn passes_over(&self, station: &Station, hours: f64) -> Vec<Pass> {
        let period = self.period_min();
        let n = (hours * 60.0 / period) as usize;
        (0..n)
            .map(|i| Pass {
                start_min: i as f64 * period,
                max_elevation: (self.inclination_deg - station.lat.abs()).abs().min(90.0),
            })
            .collect()
    }
}
