#!/usr/bin/env bash
# Creates a realistic, privacy-safe demo folder tree for Soyuz screenshots and demos
# (Linux port of scripts/demo-fixture.ps1; same tree).
#
# Everything is generated: photos are procedurally drawn landscapes, audio is synthesized,
# documents and code are sample text, and timestamps are spread over the last months from a
# fixed seed, so two runs produce the same tree. Nothing is copied from your own folders.
#
# Layout:
#   Documents/  Reports, Notes, Recipes, Travel, Manuals (Markdown, CSV, text, a small PDF)
#   Photos/     landscapes (JPEG), 2026 Summer trip/ (more JPEGs), Screenshots/ (PNG)
#   Projects/   orbit-tracker (Rust), website (HTML/CSS/JS/SVG), data-tools (Python, JSON)
#   Music/      synthesized WAV files (waveform preview)
#   Downloads/  a zip of some photos, a CSV export, a large data file (for job demos)
#   Archive/    an older copy of Documents/Reports (for the folder-compare screenshot)
#
# Usage: scripts/demo-fixture.sh [ROOT] [BIG_FILE_MB]
#   ROOT         where to create the tree (default /tmp/SoyuzDemo: short, no user name in
#                screenshots). Replaced if it exists and holds the .soyuz-demo marker.
#   BIG_FILE_MB  size of Downloads/Telemetry dump.dat (default 192; 0 skips it).
#
# Needs bash, coreutils and python3 with Pillow (python3-pillow) for the pictures.
set -euo pipefail

root="${1:-/tmp/SoyuzDemo}"
big_mb="${2:-192}"
[[ "$big_mb" =~ ^[0-9]+$ ]] || { echo "demo-fixture.sh: BIG_FILE_MB must be a number" >&2; exit 2; }
python3 -I -c 'import PIL' 2>/dev/null || {
    echo "demo-fixture.sh: needs python3 with Pillow (dnf install python3-pillow / apt install python3-pil)" >&2
    exit 1
}

if [[ -e "$root" ]]; then
    if [[ ! -e "$root/.soyuz-demo" ]]; then
        echo "demo-fixture.sh: $root exists and is not a Soyuz demo tree (no .soyuz-demo marker); refusing to replace it." >&2
        exit 1
    fi
    rm -rf -- "$root"
fi
mkdir -p -- "$root"
root="$(cd "$root" && pwd)"
echo 'Generated by scripts/demo-fixture.sh' >"$root/.soyuz-demo"

RANDOM=1957
now="$(date -d '2026-10-06 17:42:00' +%s)"

# set_age <path> <max days> [min days]: a random time in [now - max, now - min], minus up
# to ten hours.
set_age() {
    local path="$1" max="$2" min="${3:-0}"
    local span=$(((max - min) * 86400)) off=0
    ((span > 0)) && off=$(((RANDOM * 32768 + RANDOM) % span))
    local t=$((now - min * 86400 - off - (RANDOM % 600) * 60))
    touch -h -d "@$t" -- "$path"
}

# write_text <relative path> <max days> [min days] <<'EOF' … EOF
write_text() {
    local p="$root/$1"
    mkdir -p -- "$(dirname -- "$p")"
    cat >"$p"
    set_age "$p" "$2" "${3:-0}"
}

