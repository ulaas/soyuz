for f in "$arch"/*; do touch -d "@$((now - 45 * 86400))" -- "$f"; done

# Folder times last (deepest first), so creating children does not reset them.
find "$root" -mindepth 1 -type d -printf '%d\t%p\n' | sort -rn | cut -f2- | while IFS= read -r d; do
    newest="$(find "$d" -mindepth 1 -maxdepth 1 -printf '%T@\t%p\n' | sort -rn | head -n 1 | cut -f2-)"
    [[ -n "$newest" ]] && touch -r "$newest" -- "$d"
done

count="$(find "$root" -type f | wc -l)"
size="$(du -sm "$root" | cut -f1)"
echo "Demo tree ready: $root ($count files, ${size} MB)"
