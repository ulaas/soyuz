def wav(path, seconds, sample):
    rate = 22050
    n = int(rate * seconds)
    with wave.open(path, 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(b''.join(struct.pack('<h', int(max(-32767, min(32767, sample(k / rate, seconds) * 32767))))
                               for k in range(n)))

