def chime(t, ln):
    f = [523.25, 659.25, 783.99][min(2, int(math.floor(t)))]
    return 0.5 * math.exp(-3 * (t % 1.0)) * math.sin(2 * math.pi * f * t)
def rumble(t, ln):
    swell = math.sin(math.pi * t / ln)
    return 0.35 * swell * (math.sin(2 * math.pi * 55 * t) + 0.5 * math.sin(2 * math.pi * 110.5 * t) + 0.3 * math.sin(2 * math.pi * 7 * t))
