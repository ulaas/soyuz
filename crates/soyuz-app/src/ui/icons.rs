#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_icon_has_a_glyph() {
        for &id in IconId::ALL {
            assert!(!glyph(id).is_empty(), "{id:?}");
        }
    }

    #[test]
    fn glyphs_match_the_previous_constants() {
        assert_eq!(glyph(IconId::Folder), ph::FOLDER);
        assert_eq!(glyph(IconId::Star), ph::STAR);
        assert_eq!(glyph(IconId::MagnifyingGlass), ph::MAGNIFYING_GLASS);
        assert_eq!(glyph(IconId::TerminalWindow), ph::TERMINAL_WINDOW);
        assert_eq!(glyph(IconId::WarningCircle), ph::WARNING_CIRCLE);
        assert_eq!(glyph(IconId::FolderSimple), ph::FOLDER_SIMPLE);
        assert_eq!(glyph(IconId::FilePdf), ph::FILE_PDF);
    }
}
