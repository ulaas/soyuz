//! Frontend-neutral icon ids. Core code names an icon by meaning; each frontend maps
//! an [`IconId`] to its own glyph (the egui GUI: `ui::icons::glyph`, a Phosphor glyph).
//! Variants are named after the Phosphor icon the GUI draws for them.

macro_rules! icon_ids {
    ($($v:ident),* $(,)?) => {
        /// An icon, independent of how a frontend draws it.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub enum IconId {
            $($v),*
        }

        impl IconId {
            /// Every icon id.
            pub const ALL: &'static [IconId] = &[$(IconId::$v),*];
        }
    };
}

